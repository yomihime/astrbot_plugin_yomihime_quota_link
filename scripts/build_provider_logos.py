"""Validate bundled logo bytes and generate the shared offline frontend catalog.

SVG rasterization is a separate design-time step. This build step needs only the
standard library and never fetches assets, parses SVG at runtime, or imports keys.
"""

import argparse
import base64
import json
import re
import struct
from hashlib import sha256
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = Path("quota_link/presentation/assets/provider_logos")


def frontend_source(root: Path = ROOT) -> str:
    manifest = json.loads((root / ASSETS / "manifest.json").read_text(encoding="utf-8"))
    images = {}
    for asset in manifest["assets"]:
        key = asset["provider_type"]
        if not re.fullmatch(r"[a-z][a-z0-9_]*", key):
            raise ValueError("invalid fixed logo key")
        if (
            asset["file"] != f"svg/{key}.svg"
            or asset["png_file"] != f"png-128/{key}.png"
        ):
            raise ValueError("logo path must match its fixed key")
        source = root / ASSETS / asset["file"]
        png = root / ASSETS / asset["png_file"]
        if source.is_symlink() or png.is_symlink():
            raise ValueError("logo source must not be a symlink")
        data = png.read_bytes()
        if (
            len(data) > 131072
            or data[:8] != b"\x89PNG\r\n\x1a\n"
            or struct.unpack(">II", data[16:24]) != (128, 128)
            or sha256(data).hexdigest() != asset["png_sha256"]
            or sha256(source.read_bytes()).hexdigest() != asset["sha256"]
        ):
            raise ValueError(f"logo bytes do not match manifest: {key}")
        images[key] = "data:image/png;base64," + base64.b64encode(data).decode("ascii")
    mappings = manifest["providers"]
    for spec in mappings.values():
        if spec["asset"] not in images:
            raise ValueError("missing mapped logo asset")
    return (
        "// Generated by scripts/build_provider_logos.py; local PNG bytes only.\n"
        + "const images = "
        + json.dumps(images, separators=(",", ":"))
        + ";\nconst providers = "
        + json.dumps(mappings, separators=(",", ":"))
        + ";\n"
        + "export function selectProviderLogo(account = {}) {\n"
        + " let key = typeof account?.type === 'string' ? account.type : '';\n"
        + " if (key === 'openai_compatible' && account.service_profile === 'grsai') key = 'grsai';\n"
        + " if (key === 'glm_plan' && account.region === 'global') key = 'glm_plan_global';\n"
        + " const known = Object.hasOwn(providers, key);\n"
        + " const spec = known ? providers[key] : {asset:'openai_compatible',classification:'generic_unknown'};\n"
        + " return {key:known?key:'openai_compatible',src:images[spec.asset],classification:spec.classification};\n"
        + "}\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    destination = ROOT / "pages/frontend/src/provider-logo-data.js"
    expected = frontend_source()
    actual = destination.read_text(encoding="utf-8") if destination.exists() else ""
    if args.check:
        if actual != expected:
            raise SystemExit("Rebuild the frontend provider-logo catalog")
    elif actual != expected:
        destination.write_text(expected, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
